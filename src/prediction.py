"""
prediction.py — Clean prediction interface used by the Streamlit app and notebook.
"""

from __future__ import annotations

import pandas as pd
import numpy as np
from sklearn.pipeline import Pipeline
from typing import Dict, Any, Optional


def predict_cardiovascular_disease(
    pipeline: Pipeline,
    input_data: Dict[str, Any],
    feature_columns: list[str],
) -> Dict[str, Any]:
    """
    Predict cardiovascular disease risk for a single patient.

    Parameters
    ----------
    pipeline:        Fitted sklearn Pipeline (preprocessor + classifier).
    input_data:      Dict of {feature_name: value}.
    feature_columns: Ordered list of feature columns the model was trained on.

    Returns
    -------
    dict with keys:
      predicted_class  (int)
      probability      (float | None)
      risk_label       (str)
      confidence_pct   (str)
      disclaimer       (str)
    """
    # ── Validation ────────────────────────────────────────────────────────────
    missing = [c for c in feature_columns if c not in input_data]
    if missing:
        raise ValueError(f"Missing input features: {missing}")

    # ── Build single-row DataFrame ─────────────────────────────────────────────
    row = {col: [input_data[col]] for col in feature_columns}
    df  = pd.DataFrame(row)

    # ── Predict ───────────────────────────────────────────────────────────────
    pred_class = int(pipeline.predict(df)[0])

    probability: Optional[float] = None
    if hasattr(pipeline.named_steps["classifier"], "predict_proba"):
        proba = pipeline.predict_proba(df)[0]
        probability = float(proba[1])   # probability of positive class

    # ── Human-readable outputs ────────────────────────────────────────────────
    if pred_class == 1:
        risk_label = "Higher likelihood of cardiovascular disease"
    else:
        risk_label = "Lower likelihood of cardiovascular disease"

    confidence_pct = (
        f"{probability * 100:.2f}%" if probability is not None else "N/A"
    )

    disclaimer = (
        "⚠️ Educational Disclaimer: This prediction is generated by a "
        "machine-learning model trained on a research dataset. It is intended "
        "for educational and demonstration purposes only. It is NOT a medical "
        "diagnosis and should NOT replace professional medical advice. "
        "Please consult a qualified healthcare professional."
    )

    return {
        "predicted_class":  pred_class,
        "probability":      probability,
        "risk_label":       risk_label,
        "confidence_pct":   confidence_pct,
        "disclaimer":       disclaimer,
    }
